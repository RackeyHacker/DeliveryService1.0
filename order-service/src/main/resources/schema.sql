CREATE TABLE IF NOT EXISTS outbox (
 sequence BIGSERIAL UNIQUE NOT NULL,
 event_id VARCHAR(36) PRIMARY KEY, routing_key VARCHAR(80) NOT NULL, payload TEXT NOT NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS orders (
 id VARCHAR(36) PRIMARY KEY, product_id BIGINT NOT NULL, quantity INT NOT NULL,
 total DECIMAL(14,2) NOT NULL, address VARCHAR(500) NOT NULL,
 status VARCHAR(40) NOT NULL, delivery_version INT NOT NULL DEFAULT 0,
 request_id VARCHAR(80) NOT NULL, created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS order_events (
 id BIGSERIAL PRIMARY KEY, order_id VARCHAR(36) NOT NULL REFERENCES orders(id),
 status VARCHAR(40) NOT NULL, request_id VARCHAR(80) NOT NULL, created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS order_events_order_idx ON order_events(order_id,id);
CREATE TABLE IF NOT EXISTS inbox (event_id VARCHAR(36) PRIMARY KEY);
