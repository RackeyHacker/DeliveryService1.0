CREATE TABLE IF NOT EXISTS outbox (
 sequence BIGSERIAL UNIQUE NOT NULL,
 event_id VARCHAR(36) PRIMARY KEY, routing_key VARCHAR(80) NOT NULL, payload TEXT NOT NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS deliveries (
 id VARCHAR(36) PRIMARY KEY, order_id VARCHAR(36) NOT NULL UNIQUE,
 address VARCHAR(500) NOT NULL, status VARCHAR(40) NOT NULL,
 version INT NOT NULL, request_id VARCHAR(80) NOT NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS inbox (event_id VARCHAR(36) PRIMARY KEY);
